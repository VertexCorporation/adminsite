  const policy=payloads.filter(item=>item.name==='savedepartmentpermissions').at(-1).data.departments;
  assert.equal(policy.Senatus.panels['news.editor'],'write');
  assert.equal(policy.Senatus.panels['news.published'],'read');
  assert.equal(policy.Senatus.hiddenFields,undefined);
  assert.equal(policy.Senatus.hiddenChips,undefined);
  assert.equal(await page.locator('[data-dept=Senatus][data-category=publications]').getAttribute('data-level'),'mixed');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('[data-screen-dept=Senatus][data-screen-category=publications]').evaluate(el=>el===document.activeElement),true);
  await page.locator('[data-preset-dept=Senatus]').click();
  const alignment=await page.locator('.permission-presets-menu .menu-item').evaluateAll(items=>items.map(item=>({text:getComputedStyle(item).textAlign,justify:getComputedStyle(item).justifyContent,offset:item.querySelector('span').getBoundingClientRect().x-item.getBoundingClientRect().x})));
  assert(alignment.every(item=>item.text==='left'&&item.justify==='flex-start'));
  assert(Math.max(...alignment.map(x=>x.offset))-Math.min(...alignment.map(x=>x.offset))<1);
  await page.locator('.vx-popover [data-preset=read]').click();
